clc;
clear;

% Measured Type-S thermocouple voltage
Em = 17.900;      % mV
Tc = 24;          % deg C

% NIST Type-S coefficients, -50 to 1064.18 C
c1 = [ ...
0,...
5.40313308631e-3,...
1.25934289740e-5,...
-2.32477968689e-8,...
3.22028823036e-11,...
-3.31465196389e-14,...
2.55744251786e-17,...
-1.25068871393e-20,...
2.71443176145e-24];

Ec = 0;

for n = 0:8
    Ec = Ec + c1(n+1)*Tc^n;
end

fprintf('Cold junction EMF = %.9f mV\n',Ec);

Ehot = Em + Ec;

fprintf('Equivalent hot junction EMF = %.9f mV\n',Ehot);

% NIST Type-S coefficients from 1664.5 to 1768.1 C
c2 = [ ...
146.628232636,...
-0.258430516752,...
1.63693574641e-4,...
-3.30439046987e-8,...
-9.43223690612e-15];

Efun = @(T) ...
c2(1) + ...
c2(2)*T + ...
c2(3)*T.^2 + ...
c2(4)*T.^3 + ...
c2(5)*T.^4;

Thot = fzero(@(T) Efun(T)-Ehot,[1664.5 1768.1]);

fprintf('Hot junction temperature = %.2f C\n',Thot);